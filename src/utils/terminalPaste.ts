/**
 * ターミナルペースト用テキスト整形ユーティリティ
 */

/**
 * ターミナルへペーストするためのテキストを整形します。
 * - すべての改行コードバリエーション (\r\n, \r, \n) を単一のキャリッジリターン (\r) に正規化します。
 * - ブラケッティドペーストモードのエスケープシーケンス (\x1b[200~ ... \x1b[201~) で囲みます。
 *   これにより、シェルや対話型CLI (agy, Claude Code 等) がペースト中の改行ごとに即座にコマンドや
 *   メッセージを実行してしまうのを防ぎます。
 *
 * @param text クリップボードから取得した生のテキスト
 * @returns ターミナルPTYへ送信可能な整形済みテキスト
 */
export function formatTerminalPasteText(text: string): string {
  // すべての改行コード (\r\n, \r, \n) を \r に正規化
  const normalized = text.replace(/\r\n|\r|\n/g, '\r');

  // ブラケッティドペーストモードのエスケープシーケンスで囲む
  return `\x1b[200~${normalized}\x1b[201~`;
}
